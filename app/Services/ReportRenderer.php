<?php

namespace App\Services;

/**
 * ReportRenderer — the pure JSON/Markdown/HTML rendering/templating logic
 * for ReportExportService, extracted (CODE-STRUCT-DECOMPOSE) so rendering
 * is decoupled from the Eloquent-querying build*Report() methods that
 * assemble the data it renders. Zero DB/Eloquent dependency — takes an
 * already-assembled, already-redacted data array and a format string, and
 * returns the rendered content string.
 *
 * All methods are static: nothing here holds instance state, matching the
 * pure-logic seam pattern already used for internal/cef, alert_identity.py,
 * incident_aggregation.py, and ThreatHuntQueryAllowlist elsewhere in this
 * codebase.
 */
class ReportRenderer
{
    private static function renderJson(array $data): string
    {
        return json_encode($data, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE);
    }

    private static function renderMarkdown(array $data): string
    {
        $meta  = $data['export_meta'];
        $lines = [];

        $lines[] = "# {$meta['report_type_label']}";
        $lines[] = '';
        $lines[] = '> ⚠️ **Advisory Notice:** ' . ReportExportService::DISCLAIMER;
        $lines[] = '';
        $lines[] = '## Export Metadata';
        $lines[] = '';
        $lines[] = '| Field | Value |';
        $lines[] = '|-------|-------|';
        $lines[] = '| Report Type | ' . $meta['report_type_label'] . ' |';
        $lines[] = '| Generated At | ' . $meta['generated_at'] . ' |';
        $lines[] = '| Generated By | ' . $meta['generated_by'] . ' |';

        if (!empty($meta['export_reason'])) {
            $lines[] = '| Export Reason | ' . $meta['export_reason'] . ' |';
        }

        $lines[] = '| Source ID | ' . $meta['source_id'] . ' |';
        $lines[] = '';

        switch ($meta['report_type']) {
            case 'investigation':
                $lines = array_merge($lines, self::mdInvestigation($data));
                break;
            case 'response_plan':
                $lines = array_merge($lines, self::mdResponsePlan($data));
                break;
            case 'entity_risk':
                $lines = array_merge($lines, self::mdEntityRisk($data));
                break;
            case 'trace':
                $lines = array_merge($lines, self::mdTrace($data));
                break;
        }

        $lines[] = '';
        $lines[] = '---';
        $lines[] = '_Generated by XDR Platform | ' . $meta['generated_at'] . '_';

        return implode("\n", $lines);
    }

    private static function renderHtml(array $data): string
    {
        $meta  = $data['export_meta'];
        $style = self::htmlStyles();
        $title = htmlspecialchars($meta['report_type_label']);
        $by    = htmlspecialchars($meta['generated_by']);
        $at    = htmlspecialchars($meta['generated_at']);
        $disc  = htmlspecialchars(ReportExportService::DISCLAIMER);
        $srcId = htmlspecialchars($meta['source_id']);
        $reason = !empty($meta['export_reason']) ? htmlspecialchars($meta['export_reason']) : '—';

        $body = self::htmlBody($data);

        return <<<HTML
<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>{$title}</title>
<style>{$style}</style>
</head>
<body>
<div class="report-header">
  <h1>{$title}</h1>
  <div class="meta-grid">
    <div><span class="meta-label">Generated</span>{$at}</div>
    <div><span class="meta-label">By</span>{$by}</div>
    <div><span class="meta-label">Source ID</span><code>{$srcId}</code></div>
    <div><span class="meta-label">Reason</span>{$reason}</div>
  </div>
</div>

<div class="disclaimer-box">
  <strong>⚠️ Advisory Notice:</strong> {$disc}
</div>

{$body}

<div class="report-footer">
  <p>XDR Platform | {$title} | Generated {$at} | Source: {$srcId}</p>
</div>
</body>
</html>
HTML;
    }

