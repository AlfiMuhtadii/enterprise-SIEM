    private static function htmlBody(array $data): string
    {
        $type = $data['export_meta']['report_type'];
        $h = '';

        switch ($type) {
            case 'investigation':
                $h .= self::htmlInvestigation($data);
                break;
            case 'response_plan':
                $h .= self::htmlResponsePlan($data);
                break;
            case 'entity_risk':
                $h .= self::htmlEntityRisk($data);
                break;
            case 'trace':
                $h .= self::htmlTrace($data);
                break;
        }

        return $h;
    }

    private static function htmlInvestigation(array $data): string
    {
        $inv = $data['investigation'] ?? [];
        $h   = self::htmlSection('Investigation Details', self::htmlKvTable([
            'ID'         => $inv['investigation_id'] ?? '—',
            'Title'      => $inv['title'] ?? '—',
            'State'      => '<code>' . ($inv['state'] ?? '—') . '</code>',
            'Severity'   => strtoupper($inv['severity'] ?? '—'),
            'Priority'   => 'P' . ($inv['priority'] ?? '—'),
            'Created By' => $inv['creator_name'] ?? '—',
            'Assigned To'=> $inv['assignee_name'] ?? 'Unassigned',
        ]));

        if (!empty($inv['description'])) {
            $h .= self::htmlSection('Description', '<p>' . htmlspecialchars($inv['description']) . '</p>');
        }

        if (!empty($data['state_history'])) {
            $rows = array_map(fn($e) => [
                'Timestamp' => ((array)$e)['occurred_at'] ?? '',
                'From' => ((array)$e)['from_state'] ?? '',
                'To'   => ((array)$e)['to_state'] ?? '',
                'By'   => ((array)$e)['actor_name'] ?? 'system',
            ], $data['state_history']);
            $h .= self::htmlSection('State History', self::htmlTable(['Timestamp','From','To','By'], $rows));
        }

        if (!empty($data['assignment_history'])) {
            $rows = array_map(fn($a) => [
                'Assigned At' => ((array)$a)['assigned_at'] ?? '',
                'Assignee'    => ((array)$a)['assignee_name'] ?? '',
                'Status'      => ((array)$a)['is_active'] ? 'active' : 'past',
            ], $data['assignment_history']);
            $h .= self::htmlSection('Assignment History', self::htmlTable(['Assigned At','Assignee','Status'], $rows));
        }

        if (!empty($data['analyst_notes'])) {
            $noteHtml = '';
            foreach ($data['analyst_notes'] as $note) {
                $note = (array) $note;
                $noteHtml .= '<div class="note-card"><div class="note-meta"><span class="badge">' . htmlspecialchars($note['note_type'] ?? 'note') . '</span> ' . htmlspecialchars($note['created_at'] ?? '') . '</div><p>' . htmlspecialchars($note['body'] ?? '') . '</p></div>';
            }
            $h .= self::htmlSection('Analyst Notes', $noteHtml);
        }

        if (!empty($data['linked_alerts'])) {
            $rows = array_map(fn($a) => [
                'Alert Type' => ((array)$a)['alert_type'] ?? '',
                'Severity'   => ((array)$a)['severity'] ?? '',
                'Actor'      => ((array)$a)['actor_key'] ?? '—',
                'Detected At'=> ((array)$a)['detected_at'] ?? '',
            ], $data['linked_alerts']);
            $h .= self::htmlSection('Linked Alerts', self::htmlTable(['Alert Type','Severity','Actor','Detected At'], $rows));
        }

        return $h;
    }

